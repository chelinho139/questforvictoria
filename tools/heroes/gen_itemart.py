"""Write src/phaser/render/itemArt.ts from items.py (food, materials) and gear.py (equipment)."""
import json, os
from items import MEAT_PAL, LOG_PAL, MEAT_ICON, LOG_ICON, MEAT_DROP, LOG_DROP
from gear import GEAR
from backpack import backpack, PAL as BACKPACK_PAL
import ores
import craftart
import items2
import archery
def arr(rows, ind='    '): return "[\n" + "".join(f"{ind}{json.dumps(r.rstrip('.'))},\n" for r in rows) + ind[:-2] + "]"
def pal(p): return "{ " + ", ".join(f"{json.dumps(k)}: {json.dumps(v)}" for k, v in p.items()) + " }"
pals = {'meat': MEAT_PAL, 'cooked_meat': craftart.COOKED_PAL, 'log': LOG_PAL, 'iron_bar': craftart.IRON_BAR_PAL, 'gold_bar': craftart.GOLD_BAR_PAL, **{k: v[1] for k, v in ores.ICONS.items()}, **{k: v[1] for k, v in GEAR.items()}, 'pickaxe': ores.PICK_PAL, **{k: v[1] for k, v in items2.ICONS.items()}, **{k: v[1] for k, v in archery.ICONS.items()}}
icons = {'meat': MEAT_ICON, 'cooked_meat': craftart.COOKED_ICON, 'log': LOG_ICON, 'iron_bar': craftart.ingot_icon().rows(), 'gold_bar': craftart.ingot_icon().rows(), **{k: v[0].rows() for k, v in ores.ICONS.items()}, **{k: v[0].rows() for k, v in GEAR.items()}, 'pickaxe': ores.pickaxe().rows(), **{k: v[0].rows() for k, v in items2.ICONS.items()}, **{k: v[0].rows() for k, v in archery.ICONS.items()}}
# unique versions of common gear look like them (ItemDef.looks)
for k, base in {'edric_helm': 'iron_helm', 'elowen_amulet': 'vigour_amulet'}.items():
    pals[k] = pals[base]
    icons[k] = icons[base]
L = ["""import { PixelCanvas } from './pixelPainter';
import type { ItemId } from '../../data/items';

/**
 * Item art: 20×20 bag icons (like the action icons) for every item, and ground sprites for
 * items lying in the world: food and materials have their own, gear lies on the ground as
 * itself (its icon), so you see what it is before picking it up. Same HD treatment: 3–4
 * tones lit from the top-left and the hue-tinted outline. Generated by tools/heroes.
 */
""", "const PAL: Record<ItemId, Record<string, string>> = {"]
for k, p in pals.items(): L.append(f"  {k}: {pal(p)},")
L.append("};\n\nconst ICON: Record<ItemId, string[]> = {")
for k, r in icons.items(): L.append(f"  {k}: {arr(r)},")
L.append("};\n")
L.append(f"const DROP: Partial<Record<ItemId, string[]>> = {{\n  meat: {arr(MEAT_DROP)},\n  log: {arr(LOG_DROP)},\n" + "".join(f"  {k}: {arr(r)},\n" for k, (r, _) in ores.DROPS.items())
         + f"  cooked_meat: {arr(craftart.COOKED_DROP)},\n  iron_bar: {arr(craftart.INGOT_DROP)},\n  gold_bar: {arr(craftart.INGOT_DROP)},\n" + "};\n")
L.append(f"const BACKPACK_PAL = {pal(BACKPACK_PAL)};\nconst BACKPACK = {arr(backpack().rows(), '  ')};\n")
L.append(f"const HAMMER_PAL = {pal(craftart.HAMMER_PAL)};\nconst HAMMER = {arr(craftart.hammer().rows(), '  ')};\n")
L.append("""function paint(rows: string[], pal: Record<string, string>, k: number): HTMLCanvasElement {
  const w = Math.max(...rows.map(r => r.length));
  const p = new PixelCanvas(w, rows.length);
  rows.forEach((r, y) => [...r].forEach((ch, x) => ch !== '.' && pal[ch] && p.px(x, y, pal[ch])));
  return p.outline('auto', k).toCanvas();
}

/** Bag icon (22×22 with the outline). */
export function itemIcon(id: ItemId): HTMLCanvasElement {
  return paint(ICON[id], PAL[id], 0.3);
}

/** The inventory button: a leather backpack (22×22 with the outline). */
export function backpackIcon(): HTMLCanvasElement {
  return paint(BACKPACK, BACKPACK_PAL, 0.3);
}

/** The crafting button: a smith's hammer (22×22 with the outline). */
export function hammerIcon(): HTMLCanvasElement {
  return paint(HAMMER, HAMMER_PAL, 0.3);
}

/** Sprite for the item lying on the ground (HD scale): its own ground art, or the item itself. */
export function itemDrop(id: ItemId): HTMLCanvasElement {
  return paint(DROP[id] ?? ICON[id], PAL[id], 0.22);
}
""")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '../../src/phaser/render/itemArt.ts'), 'w').write("\n".join(L))



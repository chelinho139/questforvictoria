import skillicons
K = ["""import { PixelCanvas } from './pixelPainter';

/**
 * Skill icons for the action bar, spellbook and talents (20×20, 22×22 with the outline): one
 * object plus its effect, lit from the top-left. Digits and * + are glow: drawn over the
 * outline, never outlined. Generated by tools/heroes (skillicons.py).
 */
"""]
K.append(f"const PAL: Record<string, string> = {pal(skillicons.ALL)};")
K.append("const GLOW = " + json.dumps(''.join(skillicons.GLOW)) + ";\n")
for name, f in skillicons.ICONS.items():
    K.append(f"const {name.upper()} = {arr(f().rows(), '  ')};\n")
K.append("""function paint(rows: string[]): HTMLCanvasElement {
  const w = Math.max(...rows.map(r => r.length));
  const p = new PixelCanvas(w, rows.length);
  const each = (glow: boolean) =>
    rows.forEach((r, y) => [...r].forEach((ch, x) => ch !== '.' && GLOW.includes(ch) === glow && p.px(x, y, PAL[ch])));
  each(false);
  p.outline('auto', 0.3);
  each(true);
  return p.toCanvas();
}

export const SKILL_ICONS: Record<string, () => HTMLCanvasElement> = {""")
for name in skillicons.ICONS:
    K.append(f"  {name}: () => paint({name.upper()}),")
K.append("};")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '../../src/phaser/render/skillIcons.ts'), 'w').write("\n".join(K) + "\n")

